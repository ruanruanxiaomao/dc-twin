"""manifest.py - output contracts: report sidecars, artifact manifest, traceability.

OPEN_SOURCE_PLAN §4.1: keep every existing report payload unchanged; add
non-breaking `<name>.meta.json` envelopes with schema_version / UTC time /
generator / input hashes, plus one out/manifest.json that CI can re-check.
"""
from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA, OUT, CONFIG = ROOT / "data", ROOT / "out", ROOT / "config"
VERSION = "0.1.0"

SKIP_SUFFIX = (".meta.json",)
# Verifier outputs are regenerated on every check run and are intentionally
# outside the output contract (they must never invalidate the manifest).
SKIP_NAMES = {"manifest.json", "manifest_check.json", "validate_data_check_report.json"}

INPUTS = [
    "config/layout_spec.json", "config/fleet_spec.json", "config/demand_spec.json",
    "data/config.json", "config/scenarios/baseline.json",
]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def utc_now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT,
                                       text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return "n/a"


def generator() -> dict:
    build = OUT / "build_report.json"
    blender = "not-installed"
    if build.exists():
        try:
            blender = json.loads(build.read_text(encoding="utf-8")).get("blender", blender)
        except Exception:
            pass
    return {"name": "dc-twin", "version": VERSION, "git_commit": git_commit(),
            "python": sys.version.split()[0], "blender": blender}


def seed_of() -> int | None:
    try:
        return json.loads((CONFIG / "layout_spec.json").read_text(encoding="utf-8"))["site"]["seed"]
    except Exception:
        return None


def input_rows() -> list[dict]:
    rows = []
    for rel in INPUTS:
        p = ROOT / rel
        if p.exists():
            rows.append({"path": rel, "sha256": sha256(p), "bytes": p.stat().st_size})
    return rows


def report_files() -> list[Path]:
    return sorted(p for p in OUT.glob("*.json")
                  if p.name not in SKIP_NAMES and not p.name.endswith(SKIP_SUFFIX))


def write_sidecars(gen: dict, inputs: list[dict]) -> int:
    n = 0
    for p in report_files():
        try:
            payload = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        shape = "list" if isinstance(payload, list) else "dict"
        verdict = payload.get("verdict") if isinstance(payload, dict) else \
            ("PASS" if all(x.get("status") == "PASS" for x in payload) else "FAIL")
        meta = {
            "schema_version": "1.0",
            "kind": p.stem,
            "generated_at": utc_now(),
            "generator": gen,
            "shape": shape,
            "inputs": inputs,
            "verdict": verdict,
            "data_file": p.name,
            "data_sha256": sha256(p),
        }
        (OUT / (p.stem + ".meta.json")).write_text(
            json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        n += 1
    return n


def write_traceability() -> Path:
    vr = OUT / "validate_report.json"
    rows = []
    if vr.exists():
        rows = json.loads(vr.read_text(encoding="utf-8"))
    lines = ["# Acceptance traceability", "",
             "Generated by `scripts/manifest.py` from `out/validate_report.json`.", "",
             "| Check | Status | Test id | Evidence |", "|---|---|---|---|"]
    for r in rows:
        item = r["item"]
        num = item.split()[0]
        test = "tests/acceptance/test_validate.py::%s" % num
        lines.append("| %s | %s | `%s` | `%s` |" %
                     (item.replace("|", "\\|"), r["status"], test,
                      "out/validate_report.json"))
    lines += ["", "Negative tests: `tests/run_all_negative.py` (17 cases, see",
              "`out/negative_tests.json`, `out/spec_negative_tests.json`,",
              "`out/scenario_negative_tests.json`, `out/cleanroom_report.json`).", ""]
    p = OUT / "traceability.md"
    p.write_text("\n".join(lines), encoding="utf-8")
    return p


def build_manifest() -> dict:
    gen, inputs = generator(), input_rows()
    write_traceability()          # must precede artifact hashing
    n_meta = write_sidecars(gen, inputs)
    artifacts = []
    for p in sorted(OUT.rglob("*")):
        if not p.is_file() or p.name == "manifest.json" or p.name.endswith(".meta.json"):
            continue
        rel_parts = p.relative_to(OUT).parts
        # out/exp/ 是**压力实验**产物（check_reorder 缩库存/加压需求跑出来的），
        # 数字是故意失真的。把它算进交付清单，等于让"实验数据"混进"交付数据"，
        # 审阅时根本分不清哪份是产线跑的。与 .gitignore 的 out/exp/ 同口径。
        if ("exp" in rel_parts
                or "frames" in rel_parts or p.suffix in (".blend1", ".blend2")
                or p.name in ("manifest_check.json", "junit.xml",
                              "validate_data_check_report.json")):
            continue    # intermediate frames / backups / verifier's own output
        rel = p.relative_to(ROOT).as_posix()
        artifacts.append({"path": rel, "sha256": sha256(p), "bytes": p.stat().st_size})
    m = {
        "schema_version": "1.0", "kind": "artifact_manifest",
        "generated_at": utc_now(), "generator": gen, "seed": seed_of(),
        "inputs": inputs, "artifacts": artifacts,
        "counts": {"artifacts": len(artifacts), "report_sidecars": n_meta,
                   "inputs": len(inputs)},
        "notes": "UTC ISO8601; generated files are not tracked by git; "
                 "rebuild with `dc run --scope full`.",
    }
    (OUT / "manifest.json").write_text(json.dumps(m, ensure_ascii=False, indent=2) + "\n",
                                       encoding="utf-8")
    return m


def check_manifest() -> int:
    p = OUT / "manifest.json"
    if not p.exists():
        print("DC-E3001 missing out/manifest.json; run `python scripts/manifest.py` first",
              file=sys.stderr)
        return 2
    m = json.loads(p.read_text(encoding="utf-8"))
    drift = []
    for row in m["artifacts"]:
        q = ROOT / row["path"]
        if not q.exists():
            drift.append({"path": row["path"], "reason": "missing"})
        elif sha256(q) != row["sha256"]:
            drift.append({"path": row["path"], "reason": "sha256 differs"})
    for row in m["inputs"]:
        q = ROOT / row["path"]
        if not q.exists() or sha256(q) != row["sha256"]:
            drift.append({"path": row["path"], "reason": "input changed"})
    report = {"schema_version": "1.0", "kind": "manifest_check",
             "generated_at": utc_now(), "verdict": "PASS" if not drift else "FAIL",
             "checked": len(m["artifacts"]) + len(m["inputs"]), "drift": drift}
    (OUT / "manifest_check.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("MANIFEST_%s checked=%d drift=%d" %
          (report["verdict"], report["checked"], len(drift)))
    for d in drift[:10]:
        print("  DRIFT", d["path"], d["reason"])
    return 0 if not drift else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Output contracts / artifact manifest")
    ap.add_argument("--check", action="store_true", help="verify artifacts against manifest.json")
    a = ap.parse_args(argv)
    if a.check:
        return check_manifest()
    OUT.mkdir(parents=True, exist_ok=True)
    m = build_manifest()
    print("MANIFEST_OK artifacts=%d sidecars=%d inputs=%d seed=%s commit=%s"
          % (m["counts"]["artifacts"], m["counts"]["report_sidecars"],
             m["counts"]["inputs"], m["seed"], m["generator"]["git_commit"][:8]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
